// Command i18ngen writes internal/i18n/ids_gen.go: one typed id per message of the Russian catalog.
//
// Run it from the repository root (`mise run generate`). With -check it writes nothing and fails
// when the file is out of date.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
	"unicode"
)

const (
	catalogPath = "internal/i18n/locales/ru.json"
	outputPath  = "internal/i18n/ids_gen.go"
)

func main() {
	check := flag.Bool("check", false, "fail if "+outputPath+" is out of date instead of writing it")
	flag.Parse()

	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "i18ngen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	raw, err := os.ReadFile(catalogPath)
	if err != nil {
		return fmt.Errorf("read the catalog: %w", err)
	}
	var messages map[string]json.RawMessage
	if err := json.Unmarshal(raw, &messages); err != nil {
		return fmt.Errorf("parse %s: %w", catalogPath, err)
	}

	keys := make([]string, 0, len(messages))
	for key := range messages {
		keys = append(keys, key)
	}
	slices.Sort(keys)

	out, err := render(keys)
	if err != nil {
		return err
	}

	if check {
		current, err := os.ReadFile(outputPath)
		if err != nil || !bytes.Equal(current, out) {
			return fmt.Errorf("%s is out of date: run `mise run generate`", outputPath)
		}
		return nil
	}
	if err := os.WriteFile(outputPath, out, 0o644); err != nil { //nolint:gosec // a generated source file, world-readable like the rest
		return fmt.Errorf("write %s: %w", outputPath, err)
	}
	return nil
}

func render(keys []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/i18ngen from " + catalogPath + "; DO NOT EDIT.\n\n")
	b.WriteString("package i18n\n\n")
	b.WriteString("// The messages of the catalog, one id per key. Add a message to locales/ru.json, then to every\n")
	b.WriteString("// other catalog, and run `mise run generate`.\n")
	b.WriteString("var (\n")
	seen := map[string]string{}
	for _, key := range keys {
		name := identifier(key)
		if other, ok := seen[name]; ok {
			return nil, fmt.Errorf("keys %q and %q both become %s", other, key, name)
		}
		seen[name] = key
		fmt.Fprintf(&b, "\t%s = ID{key: %q}\n", name, key)
	}
	b.WriteString(")\n")
	return format.Source([]byte(b.String()))
}

// identifier turns a key such as "start.intro" into StartIntro.
func identifier(key string) string {
	var b strings.Builder
	upper := true
	for _, r := range key {
		switch {
		case r == '.' || r == '_' || r == '-':
			upper = true
		case upper:
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}
